"""chart(): bars, a line, a donut or a ring -- the Android side.

The view is ApkpyChart, a fixed class added to the project only when a
screen has a chart. It draws on a Canvas from the numbers in
``apkpy_lib/chart_rules.py`` -- its niceScale, formatNumber, labelStep and
slices are those functions written again in Java, and a test compiles them
and asks both languages the same questions. The Activity only configures it:
kind, colours, sizes, the items as JSON and a callback that receives the
tapped item.
"""

