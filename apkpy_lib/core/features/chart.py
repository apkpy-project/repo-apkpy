CODE = "U2041"


def literal_items(node, list_assignments=None):
    """The items as JSON when they are written in the source (or name a list
    that is), else None: they then come from an expression at run time."""
    if isinstance(node, ast.Name) and list_assignments and node.id in list_assignments:
        node = list_assignments[node.id]
    if node is None:
        return '[]'
    try:
        value = ast.literal_eval(node)
    except (ValueError, SyntaxError, TypeError):
        return None
    if not isinstance(value, (list, tuple)):
        return None
    return json.dumps(list(value), ensure_ascii=False)


def refuse_kind(kind, line=0):
    from ...diagnostics import ApkpyError
    raise ApkpyError(
        'chart(kind=%r) is not a chart ApkPy draws.' % (kind,),
        code=CODE,
        title='An unknown kind of chart',
        cause='ApkPy draws four kinds natively, the same on the phone and in the Previewer.',
        expected='kind="bar", "line", "donut" or "ring"',
        received='kind=%r' % (kind,),
        suggestions=['chart(items, kind="bar", screen=home)',
                     'chart(items, kind="line", fill=True, screen=home)',
                     'chart(kind="ring", value=72, max=100, screen=home)'],
        docs='https://repo-apkpy.pages.dev/ui-components/#charts',
        line=line or 0,
    )


def java_string(value):
    if value is None:
        return 'null'
    text = str(value)
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


