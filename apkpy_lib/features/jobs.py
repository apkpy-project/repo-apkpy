"""Persistent background jobs and offline queue — desktop Previewer runtime.

This mirrors the Android WorkManager pipeline generated by
``apkpy_lib.core.features.jobs``:

* the queue lives on disk (``~/.apkpy/jobs``), so it survives a restart exactly
  like WorkManager's own database survives a reboot;
* ``requires_network`` holds the queue while the machine is offline and drains
  it when connectivity returns;
* failures and ``job.retry()`` re-run the work with linear or exponential
  backoff;
* ``unique`` + ``on_conflict`` reproduce ``ExistingWorkPolicy``;
* ``observe()`` receives the same JSON status document the Activity receives
  from ``ApkpyJobs.status(...)``.

The body of ``run=`` executes off the interface thread, as a ``Worker`` does on
Android. Talk to the interface through ``job.progress(...)`` and ``observe``,
not by calling ``set_value`` on components.
"""

import json
import os
import re
import socket
import threading
import time
import uuid

from ..diagnostics import report_exception
from .. import job_rules


# Progress/message keys — the Android side uses the same two literals so a
# status document produced here is indistinguishable from the generated one.
PROGRESS_KEY = "apkpy_progress"
MESSAGE_KEY = "apkpy_message"

RETRY_POLICIES = ("exponential", "linear")
CONFLICT_POLICIES = ("append", "keep", "replace")

_MIN_BACKOFF_SECONDS = job_rules.MIN_BACKOFF_SECONDS   # WorkManager's own floor
_MAX_BACKOFF_SECONDS = job_rules.MAX_BACKOFF_SECONDS   # and ceiling
# Hosts used by _online(). Public resolvers, reached on 443 (see _reachable).
_NETWORK_HOSTS = ("1.1.1.1", "8.8.8.8")
_PROBE_TIMEOUT = 0.8
_NETWORK_CACHE_SECONDS = 1.5
_network_cache = {"online": False, "checked_at": None}
_NETWORK_RECHECK_SECONDS = 1.5
_IDLE_POLL_SECONDS = 0.25


class JobStatus(str):
    """A JSON status document that also indexes like a dictionary.

    On Android ``on_change`` receives a JSON ``String`` and ``status["state"]``
    compiles to ``_jsonGet(status, "state")``.  Returning a plain ``dict`` in
    the Previewer would work there and break on the phone, so this keeps the
    value a ``str`` (usable in f-strings, ``set_value``, ``storage.set``) while
    supporting the same key access.  It is the object-shaped sibling of
    ``ui.JsonRows``.
    """

    def _document(self):
        try:
            parsed = json.loads(str(self))
        except ValueError:
            return {}
        return parsed if isinstance(parsed, dict) else {}

    def __getitem__(self, key):
        if isinstance(key, str):
            value = self._document().get(key, "")
            # Always a string: on Android this access becomes _jsonGet(...),
            # which returns a String for numbers too.  Returning an int here
            # would make "pending " + status["pending"] work on the phone and
            # raise TypeError in the Previewer.
            return "" if value is None else str(value)
        return super().__getitem__(key)

    def get(self, key, default=""):
        value = self._document().get(key)
        return default if value is None else str(value)

    def keys(self):
        return self._document().keys()


def _safe_name(name):
    cleaned = re.sub(r"[^A-Za-z0-9_]+", "_", str(name or "job")).strip("_")
    return cleaned or "job"


def _jobs_dir():
    directory = os.path.join(os.path.expanduser("~"), ".apkpy", "jobs")
    os.makedirs(directory, exist_ok=True)
    return directory


def _has_route():
    """True when the operating system can pick a route towards the internet.

    Asking a UDP socket to connect sends no packet — it only resolves a route
    — so this is instant and unblockable.  It is a fast negative only: a
    machine with Hyper-V, WSL, VPN or VirtualBox adapters keeps a route alive
    with the Wi-Fi switched off, which is why it cannot be the whole answer.
    """
    probe = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        probe.settimeout(0.5)
        probe.connect((_NETWORK_HOSTS[0], 53))
        return not probe.getsockname()[0].startswith("127.")
    except OSError:
        return False
    finally:
        probe.close()


def _reachable():
    """True when a well-known host answers on 443.

    Port 443 rather than 53: every browser needs 443 open, so a machine with
    working internet can always reach it, while outbound 53 is commonly
    blocked and would report "offline" to someone who is online.
    """
    for host in _NETWORK_HOSTS:
        try:
            connection = socket.create_connection((host, 443), _PROBE_TIMEOUT)
            connection.close()
            return True
        except OSError:
            continue
    return False


def _online():
    """True when this machine really has internet.

    Two steps, cheap first: no route at all means offline without touching the
    network; otherwise confirm that something out there actually answers.  The
    confirmation is what makes switching the Wi-Fi off register on a machine
    whose virtual adapters keep a route up.

    The verdict is cached briefly so draining a queue of twenty items does not
    open twenty sockets.

    And first of all, the Previewer's own word: with the connection taken
    away in its status strip (see ``network``), the queue waits as it would
    on a phone with none, whatever this machine can reach.
    """
    try:
        from . import kit as _kit
        if _kit.offline():
            return False
    except Exception:
        pass
    now = time.monotonic()
    if (_network_cache["checked_at"] is not None
            and now - _network_cache["checked_at"] < _NETWORK_CACHE_SECONDS):
        return _network_cache["online"]
    verdict = _has_route() and _reachable()
    _network_cache["online"] = verdict
    _network_cache["checked_at"] = now
    return verdict


# ── interface-thread pump ───────────────────────────────────────────────────
# Observer notifications raised on a worker thread are parked here and drained
# by start_preview_pump(), which runs on the thread that owns the Tk window.

_PUMP_INTERVAL_MS = 120
_MAX_PENDING = 200

_pump = {"running": False}
_pending = []
_pending_lock = threading.Lock()


def _queue_on_main(callback, payload):
    with _pending_lock:
        _pending.append((callback, payload))
        if len(_pending) > _MAX_PENDING:
            del _pending[:-_MAX_PENDING]


def _drain_pending():
    with _pending_lock:
        batch = list(_pending)
        del _pending[:]
    for callback, payload in batch:
        JobDef._invoke(callback, payload)


def start_preview_pump():
    """Start delivering queued observer notifications on the interface thread.

    Called by ``ui.run()``, next to the audio control poll.  Doing nothing when
    there is no window yet is fine: until the Previewer opens, every
    notification comes from the interface thread anyway.
    """
    if _pump["running"]:
        return
    from .. import ui

    proxy = getattr(ui, "_app", None)
    instance = getattr(proxy, "_instance", None) if proxy is not None else None
    root = getattr(instance, "root", None) if instance is not None else None
    if root is None:
        return
    _pump["running"] = True

    def _tick():
        # Closing the Previewer destroys the window while this callback may
        # still be scheduled.  Draining then would run observers against dead
        # widgets and print a TclError on the way out, so stop first — the
        # demo explicitly asks people to close the window with work pending.
        try:
            if not root.winfo_exists():
                _pump["running"] = False
                return
        except Exception:
            _pump["running"] = False
            return
        _drain_pending()
        try:
            root.after(_PUMP_INTERVAL_MS, _tick)
        except Exception:
            _pump["running"] = False

    root.after(_PUMP_INTERVAL_MS, _tick)


def _choice(value, allowed, default, label):
    normalized = str(value or default).strip().lower()
    if normalized not in allowed:
        raise ValueError(
            "background_job(%s=...) must be one of %s — received %r"
            % (label, ", ".join(repr(item) for item in allowed), value)
        )
    return normalized


class JobDef:
    """One declared background job. Created through :func:`background_job`."""

    def __init__(self, name, run=None, requires_network=False,
                 requires_unmetered=False, requires_charging=False,
                 requires_battery_not_low=False, retry="exponential",
                 retry_seconds=30, unique=True, on_conflict="append"):
        if not callable(run):
            raise ValueError(
                'background_job("%s", run=...) needs a function to execute '
                "in the background." % name
            )
        self.name = str(name)
        self.safe_name = _safe_name(name)
        self.run = run
        self.requires_network = bool(requires_network or requires_unmetered)
        self.requires_unmetered = bool(requires_unmetered)
        self.requires_charging = bool(requires_charging)
        self.requires_battery_not_low = bool(requires_battery_not_low)
        # NOTE: stored as retry_policy, never as self.retry — the public
        # API has both a retry= keyword and a retry() method, and an
        # attribute of the same name would shadow the method.
        self.retry_policy = _choice(retry, RETRY_POLICIES, "exponential", "retry")
        self.retry_seconds = max(_MIN_BACKOFF_SECONDS, int(retry_seconds or 30))
        self.unique = bool(unique)
        self.on_conflict = _choice(
            on_conflict, CONFLICT_POLICIES, "append", "on_conflict"
        )

        self._lock = threading.RLock()
        self._queue = []
        self._current = None
        self._observers = []
        self._cancel_generation = 0
        # The facts the status is built from -- see job_rules.status_document,
        # which the phone's ApkpyJobs.status() translates. There is no stored
        # "state": it is worked out from these, the same way on both sides.
        self._waiting = []          # items sleeping through their backoff
        self._live_progress = 0     # what the running item last reported
        self._live_message = ""
        self._offline = False       # the Previewer's own network hold
        self._last = None           # the last thing that finished
        self._outcome = "success"
        self._thread = None

        self._restore()
        self._start()

    # ── persistence ─────────────────────────────────────────────────────────
    @property
    def _path(self):
        return os.path.join(_jobs_dir(), "%s.json" % self.safe_name)

    def _restore(self):
        """Reload work left over from a previous run — WorkManager does the
        same after a reboot, and the Previewer should not silently drop it."""
        try:
            with open(self._path, "r", encoding="utf-8") as handle:
                stored = json.load(handle)
        except (OSError, ValueError):
            return
        if isinstance(stored, dict) and isinstance(stored.get("last"), dict):
            # WorkManager keeps a finished job's result across a restart, and
            # so does the phone's status; so does this.
            self._last = stored["last"]
        if isinstance(stored, dict) and isinstance(stored.get("queue"), list):
            self._queue = [item for item in stored["queue"] if isinstance(item, dict)]
            if self._queue:
                print(
                    "[ApkPy job:%s] restored %d queued item(s) from the previous "
                    "session." % (self.name, len(self._queue))
                )

    def _persist(self):
        pending = list(self._waiting) + list(self._queue)
        if self._current is not None:
            pending.insert(0, self._current)
        try:
            with open(self._path, "w", encoding="utf-8") as handle:
                json.dump({"queue": pending, "last": self._last}, handle)
        except OSError:
            pass

    # ── status ──────────────────────────────────────────────────────────────
    def _status_document(self):
        with self._lock:
            running = None
            if self._current is not None:
                running = {"progress": self._live_progress,
                           "message": self._live_message,
                           "attempt": int(self._current.get("attempt", 1))}
            pending = [int(item.get("attempt", 0))
                       for item in self._waiting + self._queue]
            return job_rules.status_document(
                running, pending, self._last, self.retry_policy,
                self.retry_seconds, offline=self._offline)

    def status(self):
        """The current status as a JSON document (also indexable by key)."""
        return JobStatus(json.dumps(self._status_document()))

    def _publish(self):
        payload = self.status()
        for callback, _screen in list(self._observers):
            self._deliver(callback, payload)

    @staticmethod
    def _deliver(callback, payload):
        """Hand an observer notification to the interface thread.

        Job bodies run on worker threads, and Tk may only be touched by the
        thread that owns the window — calling ``root.after`` from here hangs
        the worker.  Off-thread notifications are therefore parked in a queue
        that :func:`start_preview_pump` drains from the interface thread, the
        same arrangement the audio control poll uses.

        With no pump running (headless scripts and tests) the callback is
        invoked directly, since there is no interface to protect.
        """
        if threading.current_thread() is threading.main_thread() or not _pump["running"]:
            JobDef._invoke(callback, payload)
            return
        _queue_on_main(callback, payload)

    @staticmethod
    def _invoke(callback, payload):
        try:
            # With no pump, job.progress() delivers here on the job's own
            # thread -- but an observer belongs to the screen, and may set a
            # label. It is not part of the body.
            with job_rules.outside_job():
                callback(payload)
        except Exception as error:  # an observer must never kill the queue
            # The queue deliberately survives a broken observer, so without a
            # full diagnostic the interface would simply stop updating with no
            # explanation anywhere.
            report_exception(
                error,
                context=(
                    "Background job observer (on_change) - the queue kept "
                    "running, but the interface stopped receiving updates "
                    "from this callback"
                ),
            )

    def _finish(self, event):
        """The item's last word: kept, persisted, and told to the screen."""
        with self._lock:
            self._last = event
            self._persist()
        self._publish()

    # ── public API ──────────────────────────────────────────────────────────
    def enqueue(self, data=None):
        """Queue one unit of work. ``data`` values are readable with
        ``job.input(key)`` inside the ``run`` function."""
        payload = {}
        for key, value in (data or {}).items():
            payload[str(key)] = "" if value is None else str(value)

        with self._lock:
            if self.unique and self.on_conflict == "keep":
                if self._current is not None or self._queue:
                    print(
                        "[ApkPy job:%s] on_conflict='keep' — work is already "
                        "pending, ignoring this enqueue." % self.name
                    )
                    return self
            if self.unique and self.on_conflict == "replace":
                self._queue.clear()
                self._cancel_generation += 1
                self._current = None
            self._queue.append(
                {"id": uuid.uuid4().hex, "data": payload, "attempt": 0}
            )
            self._persist()
        self._publish()
        return self

    def cancel(self):
        """Drop every queued item and abandon the result of whatever is
        currently running (``WorkManager.cancelUniqueWork``)."""
        with self._lock:
            self._queue.clear()
            self._waiting.clear()
            self._cancel_generation += 1
            self._current = None
        self._finish(job_rules.cancelled())
        return self

    def observe(self, on_change=None, screen=None):
        """Receive the job status whenever it changes."""
        if not callable(on_change):
            raise ValueError(
                'job.observe(on_change=...) needs a function that receives the '
                "status document."
            )
        self._observers.append((on_change, screen))
        self._deliver(on_change, self.status())
        return self

    # ── used from inside the run function ───────────────────────────────────
    def input(self, key, default=""):
        """Read one value from the payload passed to :meth:`enqueue`."""
        with self._lock:
            current = self._current or {}
        return current.get("data", {}).get(str(key), default)

    def attempt(self):
        """Which attempt this is, starting at "1" — useful to give up or to
        behave differently after a retry.

        A string, like every other value that crosses to Android, where it
        becomes ``getRunAttemptCount() + 1`` (WorkManager counts from zero).
        """
        with self._lock:
            current = self._current or {}
        return str(current.get("attempt", 1))

    def progress(self, percent, message=""):
        """Report progress (0-100) to every observer."""
        try:
            value = int(float(percent))
        except (TypeError, ValueError):
            value = 0
        with self._lock:
            self._live_progress = max(0, min(100, value))
            self._live_message = "" if message is None else str(message)
        self._publish()
        return self

    def retry(self):
        """Mark this attempt as failed so it runs again after the backoff.

        The rest of the function still executes — the outcome is decided when
        the body returns, exactly like the generated ``Worker``."""
        with self._lock:
            self._outcome = "retry"
        return self

    def fail(self):
        """Mark this attempt as permanently failed (no further retries)."""
        with self._lock:
            self._outcome = "fail"
        return self

    # ── queue drain loop ────────────────────────────────────────────────────
    def _start(self):
        if self._thread is not None:
            return
        self._thread = threading.Thread(
            target=self._drain, name="apkpy-job-%s" % self.safe_name, daemon=True
        )
        self._thread.start()

    def _backoff_seconds(self, attempt):
        return job_rules.backoff_seconds(self.retry_policy, self.retry_seconds, attempt)

    def _next_item(self):
        with self._lock:
            if not self._queue:
                return None, self._cancel_generation
            offline = self.requires_network and not _online()
        if offline:
            # Announce the hold once, then keep waiting quietly.
            if not self._offline:
                with self._lock:
                    self._offline = True
                self._publish()
            return "offline", self._cancel_generation
        with self._lock:
            self._offline = False
            if not self._queue:
                return None, self._cancel_generation
            item = self._queue.pop(0)
            item["attempt"] = int(item.get("attempt", 0)) + 1
            self._current = item
            self._outcome = "success"
            self._live_progress = 0
            self._live_message = ""
            self._persist()
            return item, self._cancel_generation

    def _report_body_failure(self, error, item):
        """Describe a crash inside ``run=`` without hiding what happens next."""
        attempt = 1
        try:
            attempt = int((item or {}).get("attempt", 1))
        except (TypeError, ValueError):
            attempt = 1
        payload = (item or {}).get("data") or {}
        keys = ", ".join(sorted(str(k) for k in payload)) or "no payload"
        report_exception(
            error,
            context=(
                "Background job '%s' - attempt %d of run=%s() raised, so the "
                "item goes back to the queue and is retried with backoff "
                "(payload keys: %s)"
                % (self.name, attempt, getattr(self.run, "__name__", "run"), keys)
            ),
        )

    def _drain(self):
        while True:
            item, generation = self._next_item()
            if item is None:
                time.sleep(_IDLE_POLL_SECONDS)
                continue
            if item == "offline":
                time.sleep(_NETWORK_RECHECK_SECONDS)
                continue

            self._publish()
            try:
                with job_rules.running_job():
                    self.run()
                outcome = self._outcome
            except Exception as error:
                if job_rules.is_refusal(error):
                    # The phone would not build this body at all. Retrying
                    # cannot help, so the job stops -- loudly, once.
                    report_exception(error, context=(
                        "Background job '%s' - run=%s() reached a call the "
                        "phone refuses inside a job, so the job stops here "
                        "instead of retrying"
                        % (self.name, getattr(self.run, "__name__", "run"))))
                    with self._lock:
                        cancelled = generation != self._cancel_generation
                        if not cancelled:
                            self._current = None
                    if not cancelled:
                        self._finish(job_rules.finished(
                            False, self._live_message, item["attempt"]))
                    continue
                # An uncaught error inside run= is treated exactly as Android
                # treats a Worker that throws: the attempt fails and the item
                # is retried.  Reported in full because the failure happens off
                # the interface thread, where nothing else would show it.
                self._report_body_failure(error, item)
                outcome = "retry"

            with self._lock:
                cancelled = generation != self._cancel_generation
                if not cancelled:
                    self._current = None
                    self._persist()

            if cancelled:
                continue
            if outcome == "retry":
                self._requeue(item, generation)
            else:
                self._finish(job_rules.finished(
                    outcome != "fail", self._live_message, item["attempt"]))

    def _requeue(self, item, generation):
        """Wait out the backoff. Meanwhile the item is still pending -- on the
        phone it is an ENQUEUED WorkInfo -- so the status says "retry"."""
        delay = self._backoff_seconds(int(item.get("attempt", 1)))
        with self._lock:
            self._waiting.append(item)
            self._persist()
        self._publish()

        def _put_back():
            time.sleep(delay)
            with self._lock:
                if item in self._waiting:
                    self._waiting.remove(item)
                if generation != self._cancel_generation:
                    return
                self._queue.insert(0, item)
                self._persist()
            self._publish()

        threading.Thread(target=_put_back, daemon=True).start()


_jobs = {}


def background_job(name, run=None, requires_network=False,
                   requires_unmetered=False, requires_charging=False,
                   requires_battery_not_low=False, retry="exponential",
                   retry_seconds=30, unique=True, on_conflict="append"):
    """Declare a persistent background job.

        sync = background_job(
            "sync_notes",
            run=sync_notes,
            requires_network=True,
            retry="exponential",
            unique=True,
        )

        sync.enqueue({"folder_id": 12})
        sync.observe(on_change=show_progress, screen=home)

    On Android this becomes a ``OneTimeWorkRequest`` driven by WorkManager:
    the queue is persisted across process death and reboots, constraints keep
    it from running on the wrong network, and failed attempts back off
    automatically.
    """
    existing = _jobs.get(str(name))
    if existing is not None:
        return existing
    job = JobDef(
        name, run=run, requires_network=requires_network,
        requires_unmetered=requires_unmetered,
        requires_charging=requires_charging,
        requires_battery_not_low=requires_battery_not_low,
        retry=retry, retry_seconds=retry_seconds, unique=unique,
        on_conflict=on_conflict,
    )
    _jobs[job.name] = job
    return job


