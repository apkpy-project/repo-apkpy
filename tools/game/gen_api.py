"""Generates apkpygame/_components.py (the stubs of components and actions) from the schema.

    python src/tools/gen_api.py [--check]

The stubs exist for the IDE (names, parameters, docs). The build never runs
them: it reads game files with the schema itself. --check fails if the file
is out of date (used by the tests).
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))      # ApkPy's repository
TOOLS = os.path.join(ROOT, "tools", "game")
SRC = ROOT
PKG = os.path.join(ROOT, "apkpy_lib", "game")
OUT = os.path.join(PKG, "_components.py")
PY_TYPES = {"number": "float", "int": "int", "string": "str", "text": "str", "bool": "bool", "color": "str",
            "pair": "Union[float, Tuple[float, float]]", "rect": "Tuple[int, int, int, int]", "enum": "str",
            "image": "Any", "sound": "Any", "font": "Any", "frame": "Union[int, str]", "actions": "Any", "dict": "dict",
            "entity": "Any", "box": "Tuple[float, float, float, float]", "tilemap": "Any", "strings": "list",
            "objects": "dict", "animations": "dict", "condition": "str"}


def signature(spec):
    parts = []
    star = None
    for arg in spec["args"]:
        if arg.startswith("*"):
            star = arg[1:]
            parts.append("*%s: Any" % star)
            continue
        f = spec["fields"][arg]
        parts.append("%s: %s%s" % (arg, PY_TYPES[f["type"]], "" if f.get("required") else " = " + repr(_default(f))))
    rest = [n for n in spec["fields"] if n not in spec["args"] and n != star]
    if rest and not star:
        parts.append("*")
    for n in rest:
        f = spec["fields"][n]
        parts.append("%s: %s = %s" % (n, PY_TYPES[f["type"]], repr(_default(f))))
    return ", ".join(parts)


def _default(f):
    d = f.get("default")
    return tuple(d) if isinstance(d, list) and f["type"] == "pair" else d


def doc(spec):
    lines = [spec.get("doc", "")]
    for n, f in spec["fields"].items():
        extra = (" " + f["doc"]) if f.get("doc") else ""
        values = (" (%s)" % ", ".join(f["values"])) if f.get("values") else ""
        lines.append("    %s: %s%s%s" % (n, f["type"], values, extra))
    return "\n    ".join(lines)


def generate():
    with open(os.path.join(PKG, "schema", "components.json"), encoding="utf-8") as fh:
        schema = json.load(fh)
    out = ['"""GENERATED by src/tools/gen_api.py from schema/components.json: do not edit.',
           "",
           "Stubs for the IDE. The build never runs them: game files are read, not executed.",
           '"""',
           "from typing import Any, Tuple, Union",
           "",
           "__all__ = %r" % ([c["name"] for c in schema["components"]] + [a["name"] for a in schema["actions"]]),
           ""]
    for c in schema["components"]:
        out += ["", "class %s:" % c["name"], '    """%s"""' % doc(c), "",
                "    def __init__(self, %s):" % signature(c), "        pass", ""]
    for a in schema["actions"]:
        out += ["", "def %s(%s):" % (a["name"], signature(a)), '    """%s"""' % doc(a), ""]
    return "\n".join(out).rstrip() + "\n"


def main():
    text = generate()
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as fh:
            if fh.read() != text:
                sys.exit("_components.py is out of date: python src/tools/gen_api.py")
        return
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
